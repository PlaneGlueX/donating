const spot = key => {
  const n = Number(key.slice(1))
  const px = (ox, oy) => [885 + ox / 32, 73.875, 356 + oy / 32]
  const even = ['low', 'even', 'red', 'black', 'odd', 'high'].indexOf(key)
  if (even >= 0) return px(10, 16 + 12 * even)
  if (key[0] === 'c') return px(19.5 + 12 * n, 85)
  if (key[0] === 'd') return px(21.5, 24 * n - 2)
  return n === 0 ? px(43.5, 5.5) : px(31.5 + 12 * ((n - 1) % 3), 12.5 + 6 * Math.floor((n - 1) / 3))
}
